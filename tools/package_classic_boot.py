#!/usr/bin/env python3
"""Assemble the Classic one-shot capsule and add it to the resident TAP."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

try:
    from check_tap_image import (
        basic_loader, code_pair, parse_blocks, parse_map, tap_block, tape_header,
        validate_classic_boot_tap,
    )
except ModuleNotFoundError:
    from tools.check_tap_image import (
        basic_loader, code_pair, parse_blocks, parse_map, tap_block, tape_header,
        validate_classic_boot_tap,
    )


BOOT_ORG = 0x6800
RESIDENT_ORG = 0x7000
BOOT_SYMBOLS = (
    "asset_load_addr",
    "asset_load_size",
    "frame_clock_frames",
    "ovl_close_overlay_file",
    "asset_filename",
    "ovl_esx_open_readonly",
    "ovl_handle",
    "ovl_read_chunked",
    "ovl_close",
    "assets_success",
    "assets_fail_close",
    "assets_fail",
    "classic_boot_frame_clock_isr",
    "_last_frame_count",
)


def write_boot_defs(map_path: Path, output: Path) -> None:
    symbols = parse_map(map_path.read_text(encoding="utf-8", errors="replace"))
    vector_symbol = "_spectrum_frame_clock_vector_reservation"
    missing = [
        name for name in (*BOOT_SYMBOLS, vector_symbol) if name not in symbols
    ]
    if missing:
        raise ValueError("resident map missing boot imports: " + ", ".join(missing))
    vector = symbols[vector_symbol]
    if vector & 0xFF != 0xFF:
        raise ValueError("Classic IM2 vector reservation must end in 0xFF")
    lines = [
        ";; AUTO-GENERATED by tools/package_classic_boot.py -- DO NOT EDIT",
        ";; Resident symbols used only during Classic cold boot",
        "",
    ]
    lines.extend(f"DEFC {name} = ${symbols[name]:04X}" for name in BOOT_SYMBOLS)
    lines.extend((
        f"DEFC frame_clock_vector_pointer = ${vector:04X}",
        f"DEFC frame_clock_vector_page = ${vector >> 8:02X}",
    ))
    output.write_text("\n".join(lines) + "\n", encoding="ascii")


def assemble_boot(
    assembler: str, source: Path, build_dir: Path, binary: Path,
) -> None:
    # z80asm writes the object at -O plus the source path as given and does
    # not create directories: pass the repo-relative path and create its
    # directory, so a fresh build/ (clone, worktree, make clean) assembles.
    root = source.parents[2]
    relative = source.relative_to(root)
    (build_dir / relative.parent).mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [
            assembler,
            "-b",
            "-m",
            f"-I={build_dir}",
            f"-O={build_dir}",
            f"-o={binary.name}",
            str(relative),
        ],
        cwd=root,
        text=True,
        errors="replace",
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        raise ValueError(result.stdout + result.stderr)
    section_binary = binary.with_name(binary.stem + "_code_boot.bin")
    if binary.stat().st_size == 0 and section_binary.exists():
        binary.write_bytes(section_binary.read_bytes())
    boot_map = parse_map(binary.with_suffix(".map").read_text(
        encoding="utf-8", errors="replace"
    ))
    expected = {
        "_spectrum_assets_load": BOOT_ORG,
        "_spectrum_frame_clock_init": 0x6833,
        "_spectrum_app_tick_init": 0x6842,
        "_spectrum_assets_fatal": 0x6849,
    }
    for name, address in expected.items():
        if boot_map.get(name) != address:
            raise ValueError(f"Classic boot symbol {name} is not 0x{address:04X}")
    size = len(binary.read_bytes())
    if size == 0:
        raise ValueError("z80asm produced an empty Classic boot capsule")
    if size > RESIDENT_ORG - BOOT_ORG:
        raise ValueError("Classic boot capsule reaches resident ORG")


def package_tap(tap: bytes, boot: bytes) -> bytes:
    blocks = parse_blocks(tap)
    if len(blocks) != 4:
        raise ValueError(f"expected standard four-block TAP, found {len(blocks)} blocks")
    if blocks[0][0] != 0 or len(blocks[0][1]) != 17 \
            or blocks[0][1][0] != 0 or blocks[1][0] != 0xFF:
        raise ValueError("input TAP does not start with BASIC")
    code_header = blocks[2][1]
    if blocks[2][0] != 0 or len(code_header) != 17 or code_header[0] != 3 \
            or blocks[3][0] != 0xFF:
        raise ValueError("input TAP does not end with resident CODE")
    if int.from_bytes(code_header[13:15], "little") != RESIDENT_ORG:
        raise ValueError("input TAP resident CODE does not load at 0x7000")

    loader = basic_loader(BOOT_ORG - 1, 2, RESIDENT_ORG)
    basic_header = tape_header(0, "Loader", len(loader), 10, len(loader))
    resident_pair = tap_block(0, code_header) + tap_block(0xFF, blocks[3][1])
    result = (
        tap_block(0, basic_header) + tap_block(0xFF, loader)
        + code_pair("BOOT", boot, BOOT_ORG) + resident_pair
    )
    validate_classic_boot_tap(
        result, boot, BOOT_ORG, RESIDENT_ORG, BOOT_ORG - 1, RESIDENT_ORG,
    )
    return result


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--map", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--build-dir", type=Path, required=True)
    parser.add_argument("--assembler", required=True)
    parser.add_argument("--tap", type=Path, required=True)
    args = parser.parse_args(argv)

    try:
        args.build_dir.mkdir(parents=True, exist_ok=True)
        defs = args.build_dir / "classic_boot_defs.asm"
        binary = args.build_dir / "SHATRANJ_CLASSIC_BOOT.bin"
        write_boot_defs(args.map, defs)
        assemble_boot(args.assembler, args.source.resolve(), args.build_dir.resolve(), binary)
        capsule = binary.read_bytes()
        packed = package_tap(args.tap.read_bytes(), capsule)
        args.tap.write_bytes(packed)
    except (OSError, ValueError) as exc:
        print(f"[ERR] Classic boot package: {exc}", file=sys.stderr)
        return 1

    print(
        f"[OK] Classic boot capsule: {len(capsule)} bytes at "
        f"0x{BOOT_ORG:04X}; TAP {len(packed)} bytes"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
