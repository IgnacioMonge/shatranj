#define NETCHESSZX_SESSION_ROUTE_CONTROL 1u
#define NETCHESSZX_SESSION_ROUTE_PRESENCE 2u
#define NETCHESSZX_SESSION_ROUTE_GAME 3u
#define NETCHESSZX_SESSION_ROUTE_ACK 4u
#define NETCHESSZX_SESSION_ROUTE_PRESENCE_PEER 5u
#define NETCHESSZX_SESSION_ROUTE_META 6u
#define NETCHESSZX_SESSION_ROUTE_CLEAR_META 0x20u
#define NETCHESSZX_SESSION_ROUTE_OFFLINE 0x40u
#define NETCHESSZX_SESSION_ROUTE_RETAIN 0x80u

/* Session-action view of the synchronous MQTT_TX request byte. */
#define NETCHESSZX_SESSION_MQTT_TX_CTX_FLAGS 2u
#define NETCHESSZX_SESSION_MQTT_TX_ROUTE_MASK 0x0fu

#endif
